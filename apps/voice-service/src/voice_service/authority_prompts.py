def authority_greeting_context(name: str) -> str:
    """Malayalam system instruction naming the caller, appended once
    bot.run_bot's lookup_authority call confirms who's calling — same
    append-after-construction convention as prompts.known_caller_context."""
    return f'വിളിക്കുന്നയാളുടെ പേര് "{name}" ആണ് — ഈ പേര് ഉപയോഗിച്ച് അഭിവാദനം ചെയ്യുക.'
